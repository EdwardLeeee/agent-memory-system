def _run_benchmark(args: argparse.Namespace, root: Path, config: Path) -> dict[str, Any]:
    os.environ["AGENT_MEMORY_HOME"] = str(root)
    os.environ["AGENT_MEMORY_CONFIG_HOME"] = str(config)
    initialize(root, "benchmark-machine")

    reserved_records = 6
    bulk_records = args.records - reserved_records
    started = time.perf_counter()
    cases = _generate_facts(root, bulk_records, args.cases)
    graph = _record_graph_fixture(root)
    scope = _scope_fixture(root, bulk_records)
    _record_startup_preferences(root)
    generation_seconds = time.perf_counter() - started

    started = time.perf_counter()
    active_count, validation_errors = validate(root)
    validation_seconds = time.perf_counter() - started
    if validation_errors:
        raise RuntimeError("synthetic store failed validation: " + "; ".join(validation_errors[:3]))
    if active_count != args.records:
        raise RuntimeError(f"expected {args.records} active records, got {active_count}")

    shutil.rmtree(root / ".cache", ignore_errors=True)
    started = time.perf_counter()
    indexed = reindex(root)
    index_seconds = time.perf_counter() - started
    index_path = root / ".cache" / "index.sqlite3"

    started = time.perf_counter()
    first_context = build_context(
        root,
        Path("/tmp/agent-memory-benchmark"),
        cases[0]["query"],
        1800,
        False,
        None,
    )
    first_query_seconds = time.perf_counter() - started
    if cases[0]["expected_id"] not in _source_ids(first_context):
        raise RuntimeError("first indexed query missed its expected record")

    warm_seconds: list[float] = []
    for index in range(args.warm_runs):
        case = cases[index % len(cases)]
        started = time.perf_counter()
        build_context(
            root,
            Path("/tmp/agent-memory-benchmark"),
            case["query"],
            1800,
            False,
            None,
        )
        warm_seconds.append(time.perf_counter() - started)

    cli_seconds: list[float] = []
    environment = os.environ.copy()
    for index in range(args.cli_runs):
        case = cases[index % len(cases)]
        started = time.perf_counter()
        result = subprocess.run(
            [
                str(PROJECT_ROOT / "bin" / "memoryctl"),
                "context",
                "--cwd",
                "/tmp/agent-memory-benchmark",
                "--query",
                case["query"],
                "--budget-tokens",
                "1800",
            ],
            cwd=PROJECT_ROOT,
            env=environment,
            text=True,
            capture_output=True,
            check=False,
        )
        cli_seconds.append(time.perf_counter() - started)
        if result.returncode != 0 or case["expected_id"] not in result.stdout:
            raise RuntimeError("end-to-end CLI query failed")

    relevance = _rank_metrics(cases, root)
    semantic_gaps = _semantic_gap_probes(root)
    session, startup_context = _session_fixture(root)
    hooks = _hook_fixture(root)
    correctness = {
        **graph,
        **scope,
        **session,
        **hooks,
    }
    if not all(correctness.values()):
        failed = sorted(key for key, value in correctness.items() if not value)
        raise RuntimeError("correctness checks failed: " + ", ".join(failed))
    if relevance["hit_at_3"] < 1.0:
        raise RuntimeError("labeled retrieval hit@3 fell below 1.0")

    return {
        "schema_version": 2,
        "generated_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        "environment": {
            "python": platform.python_version(),
            "sqlite": sqlite3.sqlite_version,
            "platform": platform.platform(),
        },
        "workload": {
            "active_records": active_count,
            "labeled_queries": len(cases),
            "warm_core_runs": args.warm_runs,
            "end_to_end_cli_runs": args.cli_runs,
            "data": "deterministic synthetic canonical Markdown records",
        },
        "scale": {
            "generation_ms": _milliseconds(generation_seconds),
            "validation_ms": _milliseconds(validation_seconds),
            "index_build_ms": _milliseconds(index_seconds),
            "indexed_records": indexed,
            "index_bytes": index_path.stat().st_size,
            "first_query_after_index_ms": _milliseconds(first_query_seconds),
            "warm_core_median_ms": _milliseconds(statistics.median(warm_seconds)),
            "warm_core_p95_ms": _milliseconds(_percentile(warm_seconds, 0.95)),
            "end_to_end_cli_median_ms": _milliseconds(statistics.median(cli_seconds)),
            "end_to_end_cli_p95_ms": _milliseconds(_percentile(cli_seconds, 0.95)),
        },
        "retrieval_usefulness": relevance,
        "semantic_gap_probes": semantic_gaps,
        "startup_context": startup_context,
        "correctness_checks": correctness,
        "claim_boundary": {
            "demonstrates": (
                "The subsystem preserves valid records, retrieves labeled targets, "
                "expands linked evidence, restores exact sessions, filters foreign-machine "
                "facts, and keeps memory hooks non-blocking in this workload."
            ),
            "does_not_demonstrate": (
                "It does not prove that an LLM makes better final decisions; that requires "
                "a blinded repeated memory-on versus memory-off model evaluation."
            ),
        },
    }


def main() -> int:
    args = _arguments()
    if args.records < 12 or args.cases < 2 or args.warm_runs < 1 or args.cli_runs < 1:
        raise SystemExit("records>=12, cases>=2, warm-runs>=1, and cli-runs>=1 are required")
    with tempfile.TemporaryDirectory(prefix="agent-memory-benchmark-") as temporary:
        base = Path(temporary)
        result = _run_benchmark(args, base / "memory", base / "config")
        if args.keep_store:
            destination = args.keep_store.expanduser().resolve()
            if destination.exists():
                raise SystemExit(f"refusing to replace existing --keep-store path: {destination}")
            shutil.copytree(base / "memory", destination)
    rendered = json.dumps(result, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    if args.output:
        output = args.output.expanduser().resolve()
        output.parent.mkdir(parents=True, exist_ok=True)
        temporary_output = output.with_suffix(output.suffix + ".tmp")
        temporary_output.write_text(rendered, encoding="utf-8")
        os.replace(temporary_output, output)
    print(rendered, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
