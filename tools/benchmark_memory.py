def _scope_fixture(root: Path, start_index: int) -> dict[str, bool]:
    local_id = _write_fact(
        root,
        start_index,
        "scopeprobe-local quartzboundary is verified on this machine.",
        scope="machine:benchmark-machine",
        priority="normal",
    )
    foreign_id = _write_fact(
        root,
        start_index + 1,
        "scopeprobe-local quartzboundary is claimed by another machine.",
        scope="machine:foreign-machine",
        priority="critical",
    )
    (root / ".cache" / "index.dirty").write_text("benchmark\n", encoding="utf-8")
    context = build_context(
        root,
        Path("/tmp/agent-memory-benchmark"),
        "scopeprobe-local quartzboundary",
        1400,
        False,
        None,
    )
    ids = _source_ids(context)
    return {
        "local_machine_fact_retrieved": local_id in ids,
        "foreign_machine_fact_filtered": foreign_id not in ids,
    }


