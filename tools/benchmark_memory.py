def _session_fixture(root: Path) -> tuple[dict[str, bool], dict[str, Any]]:
    common = {
        "state": "active",
        "paused_task": "Nothing else is paused.",
        "resume_point": "A deterministic benchmark checkpoint exists.",
        "next_action": "Read the exact session capsule.",
        "validation": "The fixture was written successfully.",
        "rollback": "Discard the temporary benchmark store.",
        "cwd": "/tmp/shared-benchmark-project",
    }
    checkpoint(
        root,
        {**common, "active_task": "Exact alpha benchmark task."},
        "benchmark-alpha",
    )
    checkpoint(
        root,
        {**common, "active_task": "Parallel beta benchmark task."},
        "benchmark-beta",
    )
    context = build_session_context(
        root,
        Path("/tmp/shared-benchmark-project"),
        "benchmark-alpha",
        source="startup",
    )
    compact_context = build_session_context(
        root,
        Path("/tmp/shared-benchmark-project"),
        "benchmark-alpha",
        source="compact",
    )
    current = context.split("## OTHER ACTIVE TASKS", 1)[0]
    correctness = {
        "exact_session_selected": "Exact alpha benchmark task." in current,
        "parallel_session_not_used_as_current": (
            "Parallel beta benchmark task." not in current
        ),
        "startup_global_preferences_included": all(
            record_id in context
            for record_id in (
                "pref.benchmark.language",
                "pref.benchmark.recoverable",
            )
        ),
        "startup_knowledge_records_excluded": all(
            marker not in context
            for marker in (
                "benchmark.fact.",
                "decision.benchmark.silent_hook",
                "experience.benchmark.stop_pressure",
            )
        ),
        "compact_parallel_tasks_excluded": (
            "OTHER ACTIVE TASKS" not in compact_context
            and "Parallel beta benchmark task." not in compact_context
        ),
    }
    metrics = {
        "estimated_tokens": estimate_tokens(context),
        "line_count": len(context.splitlines()),
        "soft_target_tokens": SESSION_CONTEXT_SOFT_TARGET,
        "hard_limit_tokens": SESSION_CONTEXT_HARD_LIMIT,
        "preference_records_included": 2,
        "knowledge_records_included": 0,
        "sections": [
            heading
            for heading, present in (
                ("current_task", "## CURRENT TASK" in context),
                ("global_user_preferences", "## GLOBAL USER PREFERENCES" in context),
                ("other_active_tasks", "## OTHER ACTIVE TASKS" in context),
            )
            if present
        ],
    }
    return correctness, metrics


